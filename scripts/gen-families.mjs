#!/usr/bin/env node
// gen-families — derive the family table the UI routes on from the contract.
//
// A family is a top-level `tags` entry of openapi.yaml, and every operation
// carries exactly one (scripts/conformance.mjs operationFamily). The adopter
// answers the generator one question per family — mine / mock / hide
// (docs/plans/plan-adopter-onboarding.md) — so the running app needs to know which
// family any given request belongs to. That table is DERIVED, never written by
// hand: adding a family to openapi.yaml stays the whole change, and
// src/api/families.generated.test.ts fails the build if the checked-in file
// has drifted from the contract.
//
// Usage: node scripts/gen-families.mjs [--check]
//   --check  exit 1 without writing when the file on disk is stale
//
// Path matching is the only subtlety. Contract paths are templated
// (/eval/cases/{case_id}), the client asks with concrete ones
// (/eval/cases/import), and a literal segment must beat a parameter — so
// routes are emitted most-literal-first and matched in order.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath, pathToFileURL } from "node:url";
import YAML from "yaml";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const CONTRACT_FILE = path.join(ROOT, "openapi.yaml");
export const OUTPUT_FILE = path.join(ROOT, "src", "api", "families.generated.ts");

const METHODS = new Set(["get", "put", "post", "delete", "patch", "head", "options"]);

/**
 * `/eval/cases/{case_id}` -> `^\/eval\/cases\/[^/]+$` — slashes escaped
 * because the output is emitted as a regex LITERAL, where a bare / would end
 * the pattern.
 */
export function pathPattern(template) {
  const body = template
    .split("/")
    .filter(Boolean)
    .map((segment) =>
      /^\{[^}]+\}$/.test(segment) ? "[^/]+" : segment.replace(/[.*+?^${}()|[\]\\/]/g, "\\$&"),
    )
    .map((segment) => `\\/${segment}`)
    .join("");
  return `^${body || "\\/"}$`;
}

const paramCount = (template) => (template.match(/\{[^}]+\}/g) ?? []).length;

/**
 * [{ template, family }] ordered for first-match wins: fewer parameters first
 * (a literal segment beats a wildcard), then longer paths, then alphabetical
 * so the output is stable across runs.
 */
export function routes(contract) {
  const found = [];
  for (const [template, item] of Object.entries(contract.paths ?? {})) {
    const families = new Set();
    for (const [method, op] of Object.entries(item ?? {})) {
      if (!METHODS.has(method) || !op) continue;
      const [tag] = op.tags ?? [];
      if (tag) families.add(tag);
    }
    if (families.size === 0) continue;
    // One tag per path holds across the contract today, and the table is
    // keyed on the path alone because buildUrl has no method in hand. If that
    // ever stops being true the generator must fail rather than pick.
    if (families.size > 1) {
      throw new Error(
        `${template} spans families ${[...families].sort().join(", ")} — the path->family table cannot represent that`,
      );
    }
    found.push({ template, family: [...families][0] });
  }
  return found.sort(
    (a, b) =>
      paramCount(a.template) - paramCount(b.template) ||
      b.template.length - a.template.length ||
      a.template.localeCompare(b.template),
  );
}

export function render(contract, { source = "openapi.yaml" } = {}) {
  const families = (contract.tags ?? []).map((t) => t.name);
  if (families.length === 0) throw new Error(`${source} declares no top-level tags`);
  const table = routes(contract);
  const unknown = table.filter((r) => !families.includes(r.family));
  if (unknown.length > 0) {
    throw new Error(
      `operations tagged with undeclared families: ${[...new Set(unknown.map((r) => r.family))].join(", ")}`,
    );
  }

  return `// GENERATED by scripts/gen-families.mjs from ${source} v${contract.info?.version ?? "?"} — do not edit.
// Regenerate with \`npm run gen:families\`; src/api/families.generated.test.ts
// fails when this file and the contract disagree.
//
// A family is a contract tag, and it is the unit the adopter answers on
// (mine / mock / hide) — see src/lib/families.ts for what the answers do.

export const FAMILIES = [
${families.map((f) => `  ${JSON.stringify(f)},`).join("\n")}
] as const;

export type Family = (typeof FAMILIES)[number];

// What each family MEANS is not repeated here: the generator's questionnaire
// reads the tag descriptions straight out of openapi.yaml
// (scripts/conformance.mjs familyDescriptions). Copying them into src/ would
// also drag the contract's prose past the invariant guards in tests/.

/**
 * Contract path -> family, ordered so the first match wins: a literal segment
 * beats a parameter one (/eval/cases/import before /eval/cases/{case_id}).
 */
const ROUTES: ReadonlyArray<readonly [RegExp, Family]> = [
${table.map((r) => `  [/${pathPattern(r.template)}/, ${JSON.stringify(r.family)}], // ${r.template}`).join("\n")}
];

/**
 * The family a request belongs to, from the CONTRACT path the client built
 * (query string excluded — buildUrl adds that separately). null = a path the
 * contract does not describe, which the caller must treat as un-answerable
 * rather than as any particular family.
 */
export function familyOfPath(path: string): Family | null {
  const bare = path.split(/[?#]/)[0];
  for (const [pattern, family] of ROUTES) {
    if (pattern.test(bare)) return family;
  }
  return null;
}
`;
}

export function loadContract(file = CONTRACT_FILE) {
  return YAML.parse(readFileSync(file, "utf8"));
}

async function main(argv = process.argv.slice(2)) {
  const check = argv.includes("--check");
  const text = render(loadContract());
  const current = existsSync(OUTPUT_FILE) ? readFileSync(OUTPUT_FILE, "utf8") : null;
  if (current === text) {
    console.log(`${path.relative(ROOT, OUTPUT_FILE)} is up to date.`);
    return 0;
  }
  if (check) {
    console.error(
      `${path.relative(ROOT, OUTPUT_FILE)} is stale — run \`npm run gen:families\`.`,
    );
    return 1;
  }
  writeFileSync(OUTPUT_FILE, text, "utf8");
  console.log(`Wrote ${path.relative(ROOT, OUTPUT_FILE)}.`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exitCode = await main();
}
